	<p class="text-indent-first">The drawings are usually made faster than the paintings. I will leave things in a drawing that I wouldn’t feel ready to leave in a painting. There is a different scale or distance in the drawings. Color considerations are different than in the painting; therefore the edges vary from those in the paintings.</p>
	<p>Of importance is color, which makes air and makes these paintings very real. These works have air; if you were in the painting, it would weigh heavy on you. It is similar to the air I experienced in Watsonville, California, summer 1962. At dusk I was driving down a long, straight road. The artichoke fields, the rows of plants went on and on in one-point perspectives slowly over rolling hills. The perspectives deepened the space and impressiveness of the night. I noticed the air. It was heavy, misty, and blue-gray. It saturated its space. I felt it pressing against the sides of the car. These works [no. 3, for example) are related to this experience; it has not been conscious thought or representation, but it is there.</p>


<H2>Working on a Painting</H2>
	
<p>A formal problem of some sort is my starting point; a study of a problem that has come up in another painting, an idea from a drawing, certain color that I might want to work with, all these things are aimed at a better understanding of painting and myself. As I work, I gradually become more involved in the problems, and the painting begins to live as a personality. There is a dialogue of give-and-take. I make demands on the painting, and it makes demands on me; hopefully, each can respond. We constantly try each other. When I am working well, I talk with a work, scold it, praise it, try to help it along. I must always be in control, yet I consider it controlled when I am consciously following the painting’s desires. </p>
	<p>This working process is similar to the rearing of a child. It is done with love and all of your honesty. It is often exasperating and a great test of your strength and will, but you do not give up. You guide it along, fill it with all of your knowledge through yourself. In the end you want to be proud of this creation. You don’t stop and tear it up when it refuses to pay heed to your attempts to help it, because you love it. You stick with it to help it, and your work stands on its own, and you are much richer for it. 
	<p>When the painting really lives, has a right to exist on its own strengths and weaknesses, I consider it finished. When I have put all I can into it, and it really breathes, I stop. There are times when a work has pulled ahead of me and goes on to become something new to me, something that I have never seen before; that is finishing in an exhilarating way. </p>
	<p>It is very difficult to come to these ideals of finishing. Old paintings often look incomplete as a result of new things that I have learned. I know that to return to them would only bring them up to certain standards, which are constantly changing. This is why I leave some paintings in these old finished states. It is a good document of my travels along with myself. </p>
 
			
			
			
