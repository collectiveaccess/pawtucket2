<p><i>The following statement was submitted by Marden in partial fulfillment of the requirements for his Master of Fine Arts Degree, Yale University, New Haven, Connecticut, May 1, 1963.</i></p>

<H2>Painting History</H2>

<p>I came to Yale after four years of intensive academic training at Boston University. There I painted from nature: the figure, still life, and portrait. At home I had a surreptitious involvement with non-objective painting. </p>
	<p>This training was important. Constant painting and drawing from nature developed a sense of the real, that which was correct and had form. It left no room for arbitraries, and one learned to see when something was wrong. </p>
	<p>I was learning my craft and developing a vocabulary. A summer at the Yale Norfolk Summer School of Music and Art was devoted to extending and expanding my painting vocabulary: I painted whatever I wanted and felt no restrictions. </p>
	<p>The academic year 1961&mdash;1962 at Yale started as an extension of the previous summer. I began to narrow in and put this vocabulary to more specific use. I did no drawings but drew in collages and etchings. (I studied many painters and was drawn into a deep study of the work of Franz Kline.) I became aware of an underlying rectilinear structure which constantly reappeared in my work. I began to concentrate on this idea of rectangles. </p>
	<p>I worked on one large painting from October to May. This painting was a giant study board upon which I worked out many ideas. The rectangular planes, color, and paint ideas took form. My color ideas tended toward tonality, and I was drawn to Kline and then Manet, whose swift accuracy of drawing and remarkable color sections held my fascination. </p>
	<p>Manet’s <i>Street Singer</i> in the Boston Museum of Fine Arts shows a woman in a brown, blue, grey dress trimmed with blue. The doors behind her are a warm brown, and the wall is an orange umber. I <i>saw</i> the warm umber, and the color fell into place; it became a total color sensation. Each part built towards this total, which came slowly, as if being mysteriously revealed. I try for this in my work. </p>
	<p>After finishing the large study, four paintings came fast. These were to be the first paintings of the thesis series. </p>
	<p>I spent the summer in Carmel, California, near Big Sur, Point Lobos, Salinas, and Watsonville. I worked on some small drawings employing an extension of the ideas of the last paintings done at school. The rectangle of the page was divided into four rectangles by a vertical and a horizontal. The color used was tonal. These works were mixed with others that were abstract landscapes, which were responses to the openness of the space I was living in. In California I was awed by space, light, and air. </p>
	<p>In 1962 and 1963 I have had to concentrate on the rectangle problems. I have been obsessed with the idea and have become fanatical about it. </p>
	<p>At the suggestion of the mid-year jury, I tried to get more of the quality of my drawings into my paintings. This led to more exploration in the use of my materials and a loosening up of the handling of my paint. </p>
	<p>These involvements have led me to Spanish painting. It is with [the Spanish painters] that one finds an uncompromising reality. They were confronted with something, and they faced up to it. No embellishments except the all-too-rare quality of humans honestly coping with themselves. They did not search for “truths” but their own truth. They smack it right up in front of you, and you have to take it. Zurbarán, Velázquez, and Goya are the ones who do this. </p>


<H2>Aims and Concerns</H2>

<p>The ground is divided into three or four large rectangles by a vertical and a horizontal. The color tends toward grey, with color strips sometimes separating the large shapes. Most of the paintings are done in predominantly cool colors. The surface is often cruddy and labored. It often shines as a result of the use of an oily medium. The surface is, to me, correct. </p>
	<p>The paintings are made in a highly subjective state within spartan limitations. Within these strict confines, confines that I have painted myself into and intend to explore with no regrets, I try to give the viewer something to which he will react subjectively. I believe these are highly emotional paintings not to be admired for any technical or intellectual reason but to be felt. The work is presented in blatantly simple language yet makes great demands on the viewer as it seems there is little to grasp on to that can get him emotionally involved. If he looks, he will see that it is a total work, the color is not colors but total color. The parts add up to a total that is an emotional experience. These paintings loom, and they are very sad and full of heavy air. </p>

<p>“Art occurs at the point where a form is sincerely honoured by an awakened spirit.”</p>

<p>“Truth cannot be forced but must be allowed to plead for itself!” </p>

<p>“There is no Other; there is only oneself facing forever the problem of one’s self discovery!”</p>

	<p>These three quotations are from Lawrence Durrell’s Clea (1960). The first one tells what I am trying to do. The second describes how I try to do it. The third explains why I do it. </p>


