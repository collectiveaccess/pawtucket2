					<H2>
						1960
					</H2>
					<p>
						On March 6, Marden exhibited a drawing in his first group exhibition at the Lyman Allyn Art Museum, New London, Connecticut.
					</p>
					<p>
						On August 20, Marden married Pauline Baez, the sister of Joan, whom he met in a coffee shop in Boston. Pauline worked as a waitress at Club 47.
					</p>
					<H2>
						1961
					</H2>
					<p>
						On March 23, a son, Nicholas Brice Marden III (Nick), was born.
					</p>
					<p>
						In the summer, Marden attended the Yale Summer School of Music and Art in Norfolk, Connecticut, on a full scholarship. He cited Bernard Chaet and Jon Schueler as teachers who inspired him there. His classmates included Chuck Close, Vija Celmins, Bill Hochhausen, Jim Olson, and David Novros. He painted landscapes and began to work abstractly.
					</p>
					<p>
						In the fall, Marden entered the School of Art and Architecture at Yale University on a partial scholarship. His teachers were Jon Schueler, Alex Katz, Jack Tworkov, Esteban Vicente, William Bailey, Bernard Chaet, Gabor Peterdi, Philip Pearlstein, Reginald Pollack, and Richard Ziemann.&nbsp;
					</p>
					<p>
						At Yale, Marden fully embraced abstraction: “Eventually I just gave up painting the figure; I think I started one self-portrait and then I just stopped.”<a href="#footnote8"><sup>8</sup></a> Among the many lessons learned from the various teachers, Marden often mentioned Vicente, who introduced him to the art of the Spanish painters Francisco de Zurbarán (1598–1664), Diego Velázquez (1599–1660), and Francisco de Goya (1746–1828)—artists who would impact Marden’s study—and Katz, who encouraged him to find his own voice, declaring, “With your sideburns and motorcycle boots, why are you trying to paint like a 60-year-old Dutch master [meaning Willem de Kooning]?”<a href="#footnote9"><sup>9</sup></a>
					</p>
					<p>
						His fellow students included Chuck Close, Janet Fish, Nancy Graves, Robert Mangold, and Richard Serra.
					</p>
					<H2>
						1962
					</H2>
					<p>
						At the invitation of his sister-in-law Joan Baez, Marden and his family spent the summer in Carmel, California. He recounted: “They had a two-car garage with a studio on top, so I got a lot of painting done there. . . . I loved the way [California] looked; it was just great. I was really excited about it. It was beautiful country down in the Monterey Peninsula. I would paint in the morning, and I'd come down for lunch and then go up and paint a little bit afterwards and then about two o'clock Nicholas would wake up and I'd take him for a walk, put him on my shoulders and we'd walk. And we'd go down to Point Lobos all the time, really beautiful, really beautiful.”<a href="#footnote10"><sup>10</sup></a>
					</p>
					<H2>
						1963
					</H2>
					<p>
						In June, Marden graduated from Yale, having won the Susan Morse Hilles prize for painting. (For the text of his thesis, see "Statement for Masters of Fine Art."[ link]) With the money that came with the award, he moved with his family to New York City, taking a small apartment at 153 Avenue C, on the Lower East Side of Manhattan. It was then a gritty neighborhood, with frequent street fights and drug addicts hanging out on the streets.
					</p>
					<p>
						Marden took a job as a guard at the Jewish Museum.
					</p>
					<p>
						On December 6, his first solo exhibition, organized by Harriet Shorr, a classmate from Yale, opened at the Wilcox Gallery, Swarthmore College, Pennsylvania.
					</p>
					<H2>
						1964
					</H2>
					<p>
						In February, a retrospective of Jasper Johns’s work opened at the Jewish Museum. Marden recalled: “I got a job as a museum guard, and I hit the Jasper Johns retrospective. And it was like the first time in my life that, aside from pictures hanging in the house at home, where I could stand and look at paintings for a long, long time. You know five hours a day. And it was a great experience. And it was a lot to look at. And I got a lot out of it.”<a href="#footnote11"><sup>11</sup></a>
					</p>
					<p>
						In the spring, Marden moved with his family to Paris, where he stayed for several months. Describing the move, Marden stated:
					</p>
					<p class="ms-4">
						I was married, and we had a son. My in-laws were nervous about our Avenue C existence and offered to bring us to Paris where, he, a physicist, was working for UNESCO. . . . What, was I going to turn down a chance to go to Paris? I had applied for all these grants to go to Europe and had been turned down by all of them. So I went to Paris. . . . While I was there I got to see Paris and go to the museums. It was very interesting because you could see that what was going on in Europe was not that much better than in the United States. I mean, put together all the museums in New York and you have about as many good paintings as there are in Paris—sort of.<a href="#footnote12"><sup>12</sup></a>
					</p>
					<p>
						He had a studio in the attic of his in-laws’ apartment and worked on drawings. Alberto Giacometti is an artist he mentioned often as having caught his attention in Paris.
					</p>
					<p>
						In another account, Marden recalled, “When I was in Paris I was just really fascinated with the walls, they were replastering and cleaning up Paris at the time . . . and I just sat and watched them plaster walls all day, do this fantastic accumulation of drips.<a href="#footnote13"><sup>13</sup></a> These observations of the old walls being restored impacted his paintings upon his return to New York.&nbsp;
					</p>
					<p>
						At the end of the summer, Brice and Pauline separated, and he returned to the same Avenue C building in New York where they had lived together and took a job at a frame shop. Nick moved to California with Pauline and regularly visited his father.
					</p>
					<H2>
						1965
					</H2>
					<p>
						Marden moved to 76 Jefferson Street, a loft building in lower Manhattan just east of Chinatown. He sublet from Jack Klein, who became known as “the loft king” because of his real estate business negotiating leases for artists and managing buildings with loft spaces in Lower Manhattan in the 1960s through the 1980s. Klein helped Marden find later studios as well; Marden named a painting for him (no. 177). Other tenants in the Jefferson Street building at the time were the artists Stephen Poleskie, Joe Overstreet, Bob Neuwirth, and Mel Edwards and the jazz musician Eric Dolphy.<a href="#footnote14"><sup>14</sup></a> In a letter to his parents dated January 18, 1966, Marden invited them to visit him at 76 Jefferson, saying, “This is the nicest place I have ever had and I am really very pleased with it and would just love to show it off.” He included a hand-drawn map with directions to the place.<a href="#footnote15"><sup>15</sup></a>
					</p>
					<p>
						Marden took a job at Chiron Press, run by Poleskie and located in the Jefferson Street building. The short-lived press made silkscreen prints for many of the Pop artists, including Robert Indiana, for whom Marden recalls working on the original <i>Love</i> poster.<a href="#footnote16"><sup>16</sup></a> Marden would salvage rejected prints and papers and use them for his own drawings.&nbsp;
					</p>
					<p>
						In December 1965 Mickey Ruskin opened Max’s Kansas City, a bar and restaurant on lower Park Avenue. It became a gathering place for artists and poets. Marden recalls meeting many artists there:&nbsp;
					</p>
					<p class="ms-4">
						Basically at one point, everybody I knew in New York, I knew through <i>Max’s Kansas City</i>. On Friday nights, I would take the bus and I’d come round the corner and see the <i>Max’s Kansas City</i> sign . . . and get right on in, and get pitchers of wine. I met de Kooning there. [John] Chamberlain introduced me to de Kooning. . . . [Andy] Warhol was kind of the subdivision. There was a very specific area that he hung out in. And [Robert] Smithson had his area; he was always grilling some poor young artist. . . . Guys like Neil Williams, and Larry Poons. I hung out a lot with Poons. I hung out a lot with Carl Andre, or rather, Carl Andre would let us sit at his knee and he would pontificate. And that was a big help, you know. He had a very definite attitude, and he had really thought it out and he could express it.<a href="#footnote17"><sup>17</sup></a>
					</p>
					<p>
						At Max’s Kansas City, Marden also met Helen Harrington, a waitress and artist, who would become his wife.
					</p>
					<H2>
						1966
					</H2>
					<p>
						In April, at the opening of <i>Primary Structures</i>, an early, influential exhibition showing the work of artists who would become known as Minimalists, held at the Jewish Museum in New York, Marden met Klaus Kertess. Along with his business partner Jeff Byers, Kertess was about to open Bykert Gallery. He visited Marden’s studio a few weeks later and offered him a show.
					</p>
					<p>
						In the summer, Marden—along with David Novros, the couple Robert Duran and Jan Sarkisian, and Clark Murray—made a road trip from New York to Los Angeles. Marden was particularly impressed with the landscape of Nebraska and later made a painting based on his memory of it (no. 41).
					</p>
					<p>
						In October, with some canvas and money advanced by Kertess, Marden left his job at Chiron Press to concentrate on finishing paintings for his first New York exhibition.&nbsp;
					</p>
					<p>
						On November 15, Marden’s first New York solo exhibition opened at Bykert Gallery with monochromatic, single-panel paintings including <i>Nebraska</i>, <i>Nico</i> (no. 37), and <i>The Dylan Painting</i> (no. 36), among others. A few works sold, and reviews appeared in the <i>New York Times</i> and <i>Artnews</i>, among other publications. Grace Glueck described Marden’s show as “one of the most minimal, reductive and rejective shows in town,” while Amy Goldin noted the “visionary, non-objective character” of the work.<a href="#footnote18"><sup>18</sup></a>
					</p>
					<p>
						In December, with help from the artist Dorothea Rockburne, Marden got a job working in Robert Rauschenberg’s studio. He recalled: “I started working at 381 Lafayette Street, helping Bob Rauschenberg adjust his new house for living and working. It was a steady part-time job—11 to 5, three days a week—doing some low-level sorting, cleaning windows, and arranging various storage space. It evolved into making coffee, answering the phone, screening calls, and generally doing everything to make it so Bob could just work.”<a href="#footnote19"><sup>19</sup></a> Marden describes his experience with Rauschenberg as being very positive. While he admired Rauschenberg greatly, he claimed not to have been influenced by his work in the same way he might have been had he worked for Jasper Johns: “We’d sit around and talk about painting and I didn’t disagree with him on that many points, you know. It’s just the pictures are much different. We’re involved with different issues. It was really good; he was very generous, and he was very helpful and it was a good experience. . . . And then eventually he said: ‘You really shouldn’t be working for me anymore.’ And he was right.”<a href="#footnote20"><sup>20</sup></a> The job lasted until the end of 1970.
					</p>
					<H2>
						1967
					</H2>
					<p>
						In June, Marden attended the Monterey International Pop Festival in California and joined the film crew for D. A. Pennebaker’s <i>Monterey Pop</i> (1968). He is listed as “assistant camera” in the film credits. He spoke of being so taken with the performance of Otis Redding at the event that he almost bungled his assignment.<a href="#footnote21"><sup>21</sup></a> Janis Joplin gave her breakthrough performance at this concert.&nbsp;
					</p>
					<p>
						Marden moved his studio to 74 Grand Street.
					</p>
					<H2>
						1968
					</H2>
					<p>
						On January 6, <i>Brice Marden: Back Series</i> opened at Bykert Gallery.
					</p>
					<p>
						On November 7, Marden and Helen Harrington married in New York. Rauschenberg acted as Helen's maid of honor.
					</p>
					<H2>
						1969
					</H2>
					<p>
						Marden moved his studio to 26 Bond Street in New York.
					</p>
					<p>
						On April 26, <i>Brice Marden: New Paintings</i> opened at Bykert Gallery. The exhibition included multi-panel paintings, including <i>Point</i> (no. 67), <i>The Dylan Karina Painting</i> (no. 63), and <i>Fave</i> (no. 64), among others.&nbsp;
					</p>
					<p>
						On September 25, Marden’s first European exhibition opened at Galerie Yvon Lambert, Paris. Before the show, he and Helen spent some time in Paris; he rented a studio and made two paintings, <i>Au Centre</i> (no. 70) and <i>D’après la Marquise de la Solana</i> (no. 73) for inclusion in the show, along with other paintings sent from New York.
					</p>
