					<H2>
						1981
					</H2>
					<p>
						On March 12, <i>Brice Marden: Paintings, Drawings, and Etchings, 1975–1980</i> opened at the Stedelijk Museum in Amsterdam and traveled to the Whitechapel Art Gallery in London.
					</p>
					<H2>
						1982
					</H2>
					<p>
						In the early 1980s Marden suffered what he later described as a midlife crisis; he and Helen separated, he moved into his studio, took a lot of drugs, and began a relationship with another woman. Admitting to his drug use, he said: “I used to smoke marijuana all the time. It was built into the philosophy of the paintings. But then you hit middle age, and your metabolism is different. It just makes you tired, and you can’t get the work done.”<a href="#footnote30"><sup>30</sup></a> He eventually quit using drugs and alcohol and reunited with Helen and his children.&nbsp;
					</p>
					<p>
						On October 29, <i>Brice Marden: Marbles, Paintings, and Drawings</i> opened at Pace Gallery. Besides many works done on pieces of marble made during the summer of 1981 in Hydra, the exhibition included <i>Elements I</i> and <i>Elements II</i> (nos. 204, 205), among other paintings.
					</p>
					<H2>
						1983
					</H2>
					<p>
						In June, Marden traveled with his family and Jessica Craig-Martin, now a photographer but then a nanny to Mirabelle and Melia, to Tangier, where he taught painting at an International Studies program run by the School of Visuals Arts, New York. They lived for six weeks at the Hotel Villa de France, staying in the rooms Henri Matisse had occupied seventy years earlier. He visited Fez and Marrakech to see Islamic architecture. The family then traveled through Spain and southern France, ending up in Greece.&nbsp;
					</p>
					<p>
						In December, with Helen leading the way, the family left Greece and spent three months traveling in Thailand, Sri Lanka, and India.&nbsp;
					</p>
					<H2>
						1984
					</H2>
					<p>
						In January, Marden wrote to his dealer Arne Glimcher: “Thailand is beautiful, distant, not too mysterious and filled with believably beautiful houses and simple wood furniture. The wood, lumber, impresses me the most. The landscape is one that would produce Buddhism. With this travel I become more convinced that the art comes out of the landscape. It always looks just like it. Rocks in the sea look like reclining buddhas etc. . . . Limestone formations, small eruptions that become mountains. Sculptural scale. The clouds do not flow along the horizon but move independently of it, turning in convolutions that surprise this western eye.”<a href="#footnote31"><sup>31</sup></a>&nbsp;
					</p>
					<p>
						Describing a part of the trip that directly affected his art, he said: “We went south, and I started collecting seashells at the beach. These old women were selling shells they had collected and cleaned. We were at a place called Krabi, in southwestern Thailand, and it was quite beautiful. I began to draw the shells, or draw the marks on the shell, and I had one that looked like calligraphy.”<a href="#footnote32"><sup>32</sup></a> Marden’s interest in calligraphy, sparked by this trip, would grow in time.
					</p>
					<p>
						In February, the family moved on to Sri Lanka, where Marden was particularly impressed by the temple of Gal Vihara. He said: “Going to Polonnaruwa for me was like going to the Rothko Chapel. The same thing. You’ve got one cliff, and they’ve carved like a forty-foot-long reclining Buddha attaining Nirvana. There’s another Buddha in a cave; there’s a standing figure in a cave. . . . And it’s all cut out of this one thing. And it’s beautiful sculpture. I mean the depiction of the drapery is as good as anything you find in Archaic Greek sculpture. So that was a very elevating moment.”<a href="#footnote33"><sup>33</sup></a>
					</p>
					<p>
						The family continued to Madras, India, where they visited with the artist Francesco Clemente and his family. They returned to New York in March.
					</p>
					<p>
						Marden joined the board of directors for <i>Bomb</i> magazine, a quarterly publication founded in 1981 by a group of artists and writers to focus on new art, writing, theater, and film. He served on the board until the mid-1990s.&nbsp;
					</p>
					<p>
						On September 28, <i>Brice Marden: Recent Work</i> opened at Pace Gallery. The exhibition included more of the <i>Elements</i> group (nos. 228–229) as well as <i>Number One</i> (no. 225) and <i>Number Two</i> (no. 226).
					</p>
					<p>
						In October, an exhibition called <i>Masters of Japanese Calligraphy, 8th–19th Century</i> opened at the Japan House Gallery and the Asia Society in New York. With Helen’s encouragement, Brice visited the exhibition and was so impressed by it that he bought several copies of the catalogue so he could have one for reference in each of his studios. He explained that he thought of himself as a Western artist: “I didn’t want to get involved in Eastern ideologies. But that show really got me. . . . I loved the look of it—the fact that it could be so expressive and yet tied to a form, the word—whether you could understand it or not.”<a href="#footnote34"><sup>34</sup></a>&nbsp;
					</p>
					<H2>
						1985
					</H2>
					<p>
						Marden moved his studio to 276 Bowery.
					</p>
					<p>
						Marden ended his association with the Pace Gallery: “I was at a mid-life crisis. . . . I decided to leave my uptown gallery. I also stopped drinking and doing drugs. I was making a kind of painting I could have gone on making the rest of my life—a kind of signature style. Which was fine, except that I was finding it increasingly boring.”<a href="#footnote35"><sup>35</sup></a>
					</p>
					<p>
						Mary Boone offered Marden a $1 million advance on future sales if he would join her gallery. With the money, “I really could afford to take the time to work out something different that had much more to do with how the drawings worked.”<a href="#footnote36"><sup>36</sup></a> His association with the gallery lasted until around 1990.
					</p>
					<H2>
						1987
					</H2>
					<p>
						<i>Thirty-Six Poems by Tu Fu, Translated by Kenneth Rexroth with Twenty-Five Etchings by Brice Marden</i>&nbsp;was published by Peter Blum Edition. The introduction to the etchings was written by the poet and art critic John Yau, who would write extensively about Marden’s work throughout the remainder of his career. These etchings were the first realization of Marden’s experimentation with calligraphy to appear in public.
					</p>
					<p>
						On March 7, <i>Brice Marden</i> opened at the Mary Boone Gallery. This was the first showing of paintings that had evolved from his effort to bring more drawing into his painting. It included <i>Untitled #1</i> (no. 263) and <i>Diptych</i> (no. 272), among other paintings.
					</p>
					<H2>
						1988
					</H2>
					<p>
						The Mardens purchased a new home on Saint Luke’s Place in Greenwich Village, New York.&nbsp;
					</p>
					<p>
						On April 9, <i>Brice Marden</i> opened at Mary Boone Gallery in New York. Exhibited were paintings from a numbered group, including <i>3&nbsp;</i>(no. 278), <i>4 (Bone)</i> (no. 279), and <i>11 (to Leger)</i> (no. 286).
					</p>
					<H2>
						1989
					</H2>
					<p>
						On May 12<i>, Brice Marden</i> opened at the Michael Werner Gallery in Cologne. It included his <i>Couplets</i> (nos. 291–294) and <i>Cold Mountain 1 (Path)</i> (no. 300).
					</p>
					<p>
						Marden was awarded the Skowhegan Medal for Painting.
					</p>
					<p>
						Marden acquired the building on Hydra that would become his painting studio. Previously, he had made only small works in Greece. About the new studio, Marden said: “The great thing about that studio in August is that it’s hot and dry. . . . You can paint in the morning, have a big lunch, go for a swim and come back in the afternoon, and the paint’s dry.” He believed the paintings made in Greece were different than those made in his other studios: “Because the light is so bright there, you have to bring the painting up to that light. . . . The Greek pictures are much more high intensity, pure chroma colors.”<a href="#footnote37"><sup>37</sup></a>
					</p>
