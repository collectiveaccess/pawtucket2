					<H2>
						1970
					</H2>
					<p>
						Marden started teaching at the School of Visual Arts, a position he kept until 1974. Describing his job, he said: “I teach second year painting. It's a workshop. I teach in a very loose way, let them do whatever they want to do. Basically, I'm trying to get them somewhat excited about art.”<a href="#footnote22"><sup>22</sup></a>
					</p>
					<p>
						In the summer, Marden was a resident faculty member at the Skowhegan School of Painting and Sculpture in Maine. He served on the faculty again in 1971 and 1972 and was a visiting artist in the summers of 1976 and 1991. From 1972 to 1976 he was on the board of governors. In an oral history interview for the school, Marden recalled being a token abstract painter among mostly realist painters on the faculty in the early years. He describes the place as "red barns and a blue-gray sky, with a really strange light."<a href="#footnote23"><sup>23</sup></a>
					</p>
					<p>
						On October 31, <i>Brice Marden</i> opened at Bykert Gallery. The exhibition included new paintings, several of which were three-panel works, including <i>Three Deliberate Greys for Jasper Johns</i> (no. 84), <i>For Pearl</i> (dedicated to Janis Joplin; no. 82), and <i>Range</i> (no. 83).
					</p>
					<H2>
						1971
					</H2>
					<p>
						Helen Marden visited Hydra, Greece, for the first time and convinced Brice to join her for a three-week stay. They purchased their first property there in 1973 and continued to visit most summers. Of Hydra, Brice said: “It’s the last big island in Greece with no cars. There are just donkeys, mules, and maybe a few golf-cart type buggies used for emergencies. The island has a kind of landmark status, so you can’t do any building that’s not in line with what’s already there. . . . Hydra is still raw. That’s what I like about it.”<a href="#footnote24"><sup>24</sup></a> He was attracted by the light: “The light—it’s almost a cliché, the light is incredible. It sort of changes your whole idea about the kind of clarity that’s possible.”<a href="#footnote25"><sup>25</sup></a>
					</p>
					<H2>
						1972
					</H2>
					<p>
						In February, Marden went to Captiva Island on the Gulf coast of Florida at Rauschenberg’s invitation to make a series of prints. His <i>Untitled Press Series</i>, six lithographs that took the name of the press imprint, were done there, and the landscape inspired some later paintings (see nos. 80, 87)
					</p>
					<p>
						Marden visited Houston to see the newly opened Rothko Chapel. He said: “I went and I stayed at the Warwick Hotel, and I went back and forth between the hotel and the Chapel so I could see it. I liked the idea of seeing the Chapel at different times of the day.” Marden claimed to have been indebted to the Rothko paintings in the Chapel: “Basically, I was very involved with the idea of the wall, the wall painting, the Roman wall painting, and so was Rothko. He was a big help for me, and that’s my indebtedness—in a way, [the Chapel] was my teacher.”<a href="#footnote26"><sup>26</sup></a>
					</p>
					<H2>
						1973
					</H2>
					<p>
						On February 24, <i>Brice Marden, New Paintings: Grove Group</i> opened at Bykert Gallery.
					</p>
					<p>
						In May, an article titled “Brice Marden’s Painting” by Roberta Smith appeared in <i>Arts Magazine</i>. It was one of the first long essays to focus on Marden’s work. Smith has continued to write about Marden’s work thoughout her career.
					</p>
					<H2>
						1974
					</H2>
					<p>
						On January 24, Marden’s first museum show, a traveling exhibition of drawings organized by the Contemporary Arts Museum in Houston, opened. Instead of a catalogue, <i>Suicide Notes</i>, an artist’s book that reproduced seventy drawings from a single notebook at the size and in the order in which they were made, was published by Paul Bianchini.
					</p>
					<p>
						On March 23, <i>New Paintings, Brice Marden</i> opened at Bykert Gallery. It included <i>First Figure</i> <i>(Homage to Courbet)</i> (no. 139) and <i>Second Figure</i> (no. 140), among other paintings, and was his last solo exhibition at the gallery.
					</p>
					<p>
						On October 24, <i>Brice Marden: Paintings, Drawings, Etchings</i> opened at the Locksley Shea Gallery in Minneapolis. The exhibition included the <i>Red Yellow Blue</i> group (nos. 143–146) of paintings.
					</p>
					<p>
						In October, Marden’s painting <i>Red Yellow Blue IV</i>&nbsp;(no. 146) was reproduced on the cover of <i>Artforum</i> to illustrate Jeremy Gilbert-Rolfe’s “Brice Marden’s Painting.” This article bought important attention to Marden’s work.
					</p>
					<H2>
						1975
					</H2>
					<p>
						Marden moved his studio to 105 Bowery.&nbsp;
					</p>
					<p>
						On March 7, Marden’s first major museum exhibition of paintings opened at the Solomon R. Guggenheim Museum in New York.
					</p>
					<p>
						Bykert Gallery closed.
					</p>
					<H2>
						1976
					</H2>
					<p>
						The Mardens purchased a home on West Twelfth Street in Greenwich Village.&nbsp;
					</p>
					<H2>
						1977
					</H2>
					<p>
						In December, Marden traveled to Rome for a solo exhibition at Galleria Gian Enzo Sperone and visited Pompeii while he was in Italy.
					</p>
					<p>
						The documentary film <i>Brice Marden</i>, directed by Edgar Howard and Theodore R. Haimes and produced by Tuckernuck Productions, was released. It contains footage from 1968 of Marden painting and interviews conducted in 1975.
					</p>
					<H2>
						1978
					</H2>
					<p>
						The Mardens visited Morocco. The artist said: “We drove around Morocco and really saw beautiful things. I’ve never seen any landscape as beautiful as that. And then there were other things we saw, like old men, sitting in the trees, staring off into the sunset—just great, really great. And everything was beginning to grow, so it was just little sprinklings of green, and it was red earth. And then you go up into the Atlas Mountains, and it’s red granite, and you see sunsets reflected on that. Color is a way of arriving at light. The illusion of light is one of the things that a painter works with, I mean, that’s how you get an image. Without light there is no visible image.”<a href="#footnote27"><sup>27</sup></a>
					</p>
					<p>
						Marden began work on a commission to design fifteen stained-glass windows for the Basel Cathedral in Switzerland, a medieval building that rises above the town on the banks of the Rhine River. The windows were to occupy three layers of space in the choir section of the church, including four Romanesque rounded-arch windows, six Gothic rose windows above those; and five Gothic lancet windows in the clerestory area on top. Marden recalled, “The reason I decided to work on the commission was to push my work.”<a href="#footnote28"><sup>28</sup></a> His consideration of the themes and formal elements of this commission would influence many of his paintings and drawings until 1985, when it became clear the project would not be realized.
					</p>
					<p>
						On September 23, <i>Brice Marden: Recent Paintings and Drawings</i> opened at Pace Gallery, New York. The exhibition included the <i>Annunciation</i> group of paintings (nos. 169–173). This exhibition began an affiliation with Pace that lasted until 1985.
					</p>
					<p>
						On November 15, the Mardens’ first daughter, Maya Mirabelle Zahara, was born. Marden reflected: “Having Mirabelle was a shocking, eye-opening experience. . . . I was painting along and I got pretty involved in seeing art and the whole idea of creativity as incredibly important. In a way, Mirabelle’s birth disillusioned me about art. I realized that what I had been making were, after all, just paintings. They’re not alive; they’re not living things growing.... After Mirabelle... a different reality came into my painting because I no longer deluded myself about the possibilities of art. I still think there are great possibilities for art, but I now see those possibilities with the family as a constant reference point.”<a href="#footnote29"><sup>29</sup></a>
					</p>
					<H2>
						1979
					</H2>
					<p>
						On September 19, Marden’s first solo museum exhibition in Europe, a retrospective exhibition of drawings, opened at the Kunstraum München, Munich, and traveled to the Institut für Moderne Kunst, Nuremberg, Germany.
					</p>
					<p>
						The Mardens visited Ponape, Micronesia, as part of “Word of the Mouth,” an artists’ conference organized by the artist Tom Marioni and Kathan Brown of Crown Point Press. Twelve artists participated, sharing remarks about their work that were recorded for an LP record.
					</p>
					<p>
						Marden moved his studio to 54 Bond Street.&nbsp;
					</p>
					<p>
						The Mardens made their first visit to St. Barts, a French-speaking island in the Caribbean, which they would continue to visit many times over the years.
					</p>
					<p>
						On June 24, the Mardens’ second daughter, Melia Io Bricia Marden, was born.
					</p>
					<p>
						On September 26, <i>Brice Marden: New Paintings and Drawings</i> opened at Pace Gallery. The show included <i>Thira</i> (no. 178), among other paintings.
					</p>
