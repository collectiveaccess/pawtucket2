				<div class="col-12 col-md-6">
					<H2>
						2000
					</H2>
					<p>
						Marden received an honorary doctor of fine arts degree from Brown University, Providence.
					</p>
					<p>
						On November 17, <i>Brice Marden</i>, an exhibition of mostly recent work, opened at the Serpentine Gallery in London.
					</p>
					<H2>
						2001
					</H2>
					<p>
						Marden moved into his studio at 495 West Street in New York. The penthouse space housed separate studios for Brice and Helen, and its huge two-story windows looked west toward the Hudson River. About this studio, Marden said, “You always think you’re going to get the really great studio someday. . . . This is it, because I had a hand in designing it.” Continuing, he stated: “In New York we have very silvery light. . . . All that stone and glass and then the Hudson—this reflection has a huge effect on the light. Silver gives things a kind of clarity and focus.”<a href="#footnote48"><sup>48</sup></a>
					</p>
					<p>
						On December 12, <i>Brice Marden: Works on Paper, 1964–2001</i> opened at the Instituto Nazionale per la Grafica in Rome. It traveled to the&nbsp;Archivio di Stato in Turin, Italy, and the&nbsp;Westfälisches Landesmuseum für Kunst und Kulturgeschichte in Münster, Germany.
					</p>
					<H2>
						2002
					</H2>
					<p>
						On May 4, <i>Brice Marden: Attendants, Bears, and Rocks</i> opened at the Matthew Marks Gallery, New York.&nbsp;
					</p>
					<p>
						After the 9/11 terrorist attack in New York City, the Mardens sought a refuge closer to the city than their Pennsylvania home. They purchased Rose Hill, a somewhat dilapidated mid-nineteenth-century mansion with several outbuildings set on forty acres of land on the banks of the Hudson River in Tivoli, New York. The property had been an orphanage and a commune at points during its history; at one time, Dorothy Day, the social activist, ran the Catholic Worker Movement from the place. The Mardens renovated the house and several of the other buildings to create a living space and studios. Brice liked the location for its isolation, closeness to his childhood home, and ties to the nineteenth-century American Hudson River school painters, who painted scenes like those he could see from his studio window: Frederic Church’s (1826–1900) house, Olana, is nearby, and Thomas Cole’s (1801–1848) is across the river.<a href="#footnote49"><sup>49</sup></a> This studio provided the space for Marden to paint his largest works. The Mardens continued to acquire other properties in the area in the following years.&nbsp;
					</p>
					<H2>
						2003
					</H2>
					<p>
						Marden created the set designs for the opera <i>Orfeo ed Euridice</i> by Christoph Willibald Gluck, performed at the Teatro de San Carlo in Naples, Italy, under the direction of Karole Armitage.
					</p>
					<H2>
						2004
					</H2>
					<p>
						On May 8, <i>Brice Marden: Paintings on Marble</i> opened at Matthew Marks Gallery, New York.
					</p>
					<p>
						The Mardens purchased their first property on Nevis, a Caribbean island.
					</p>
					<H2>
						2005
					</H2>
					<p>
						The Mardens purchased Golden Rock Inn on Nevis and continued to manage the operation of the hotel. Marden made a studio there in 2006, explaining: “The studio in Nevis is much smaller [than my other studios]. My wife and I own a hotel there, and it has these units with a bedroom, bathroom, and porch. I just knocked a wall down and doubled the unit. Now it has a porch with a big table where I draw and look out across a field. And beyond that there’s the Caribbean. It’s not that I’m drawing it, but it’s a big help.”<a href="#footnote50"><sup>50</sup></a>
					</p>
					<H2>
						2006
					</H2>
					<p>
						In January, <i>Correspondences Musée d’Orsay/Contemporary Art: Brice Marden /Gustave Courbet</i>, opened at the Musée d’Orsay in Paris. The exhibition included a painting of Marden’s called <i>Extremes</i> (no. 368) along with a painting selected by Marden from the collection of the Musée d’Orsay called <i>The Trout</i> (1873) by Gustave Courbet. Marden said of Courbet’s painting: “My first impression was that it’s incredibly poignant. It’s beautifully painted. The paint is really making the image, the drawing comes from the painting—a kind of direct <i>manière</i>.”<a href="#footnote51"><sup>51</sup></a>
					</p>
					<p>
						Marden’s first studio space at Rose Hill was completed. He began to spend more time working there, as he found the environment conducive to painting: “There’s a very beautiful light up here coming off the river. I mean, sometimes the light is just like, you get this late afternoon light which is just like thrillingly special. So much of painting is just about light. The pigment is just some sort of substance which reacts to light.”<a href="#footnote52"><sup>52</sup></a> In 2010 and 2016 he had more buildings converted into studio spaces. He also worked on the landscape: “I spend a lot of time just wandering around the garden. I garden by attrition. That’s my hobby, is basically weeding the moss. I’m trying to make these large patches of moss, and I like sort of large monochromatic areas. So, I get this myrtle which seems to be growing all out in the woods so it’s easy to just say, get me a lot of myrtle and we’ll put it here. There’s myrtle, juniper and bamboo and moss.”<a href="#footnote53"><sup>53</sup></a>
					</p>
					<p>
						In October, <i>Brice Marden: A Retrospective of Paintings and Drawings</i> opened at the Museum of Modern Art, New York. The show traveled to the San Francisco Museum of Modern Art and the&nbsp;Nationalgalerie im Hamburger Bahnhof–Museum für Gegenwart in Berlin. Speaking of the exhibition at the Museum of Modern Art, Marden said: “This is my museum, you know, I was brought up on this museum. . . . I’m a New York painter.”<a href="#footnote54"><sup>54</sup></a>
					</p>
					<H2>
						2007
					</H2>
					<p>
						In February the Mardens left for a six-week trip to Asia. While in Taipei, they went to see the National Palace Museum, which had reopened after an extensive renovation with a major exhibition of art of the Northern Song dynasty (960–1127). Marden was particularly captivated by an example of Song dynasty calligraphy showing a poem by Huang T’ing-chien called “Seven-Character Verse.” Its formatting, mounted with borders on each vertical edge, would influence the look of his <i>Letter</i>&nbsp;paintings (nos. 375–383, 387–389, 474). Similarly, he studied the largest gathering of Ru ware pottery ever assembled for the color, deciding later in the trip to “do a painting about the Ru ware, trying to remember the color.” (see no. 406)<a href="#footnote55"><sup>55</sup></a>
					</p>
					<p>
						Marden was awarded an honorary doctor of fine arts degree from Boston University’s College of Fine Arts.
					</p>
					<p>
						On November 10, <i>Brice Marden: Complements</i> opened at Matthew Marks Gallery, New York.
					</p>
					<H2>
						2008
					</H2>
					<p>
						Marden was awarded the Alexei von Jawlensky Prize by the Museum Wiesbaden in Germany. The museum organized <i>A Retrospective of Prints</i>, which opened on September 28 in recognition of the award. The exhibition traveled to the Museum Kurhaus in Kleve, Germany.
					</p>
