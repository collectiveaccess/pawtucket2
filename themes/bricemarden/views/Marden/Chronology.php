					<H2>
						2020
					</H2>
					<p>
						On February 21, <i>Think of Them as Spaces: Brice Marden’s Drawings</i> opened at the Menil Drawing Institute in Houston. It closed shortly thereafter due to the COVID-19 pandemic. The Mardens, including their daughters and their families, isolated themselves in Tivoli during this time. While taking the necessary precautions to avoid illness, Marden said: “[The] quarantine is exactly what a painter wants. You’re just locked away in your own studio and there are no visitors. The isolation that everybody thinks is so horrible is really an ideal working situation for a painter.”<a href="#footnote60"><sup>60</sup></a>
					</p>
					<p>
						The Mardens established a foundation to purchase St. Sylvia’s Church, a historic deconsecrated Catholic church in Tivoli, and turn it into a community center and cultural facility. When the church was purchased, the original stained-glass windows were removed by the Archdiocese of New York. As one of his last projects, Marden designed the replacement windows, which will be posthumously installed (nos. 484–491).
					</p>
					<H2>
						2021
					</H2>
					<p>
						In June, Marden fell and broke his hip. He never recovered full mobility after this injury and was largely confined to a wheelchair for the rest of his life. He continued to work and travel extensively.
					</p>
					<p>
						On November 13, <i>Brice Marden: These paintings are of themselves</i> opened at Gagosian’s 541 West Twenty-Fourth Street gallery in New York. The exhibition included <i>Rocks</i> (no. 464), <i>Rivers</i> (no. 471), and <i>Belle’s Turquoise</i> (no. 473), among other paintings.
					</p>
					<H2>
						2022
					</H2>
					<p>
						In May, <i>Brice Marden: Inner Space</i> opened at the Kunstmuseum Basel. This exhibition was a revised and expanded version of <i>Think of Them as Spaces: Brice Marden’s Drawings</i>, which opened at the Menil Drawing Institute in Houston shortly before the COVID-19 pandemic.
					</p>
					<H2>
						2023
					</H2>
					<p>
						On May 20, <i>Brice Marden and Greek Antiquity</i> opened at the Museum of Cycladic Art in Athens.
					</p>
					<p>
						On August 10, Brice Marden died at his home in Tivoli.
					</p>
					<p>
						On November 2, <i>Let the painting make you</i>, an exhibition of Marden’s final works, opened at the Gagosian gallery at 980 Madison Avenue in New York.
