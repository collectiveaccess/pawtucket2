					<H2 class="mt-0">
						1938–56
					</H2>
					<p>
						Nicholas Brice Marden Jr. was born on October 15, 1938, in Bronxville, New York, to Nicholas Brice Marden, a mortgage broker, and Kathryn Fox Marden, a homemaker. He was the second of three children, with an older brother, Michael (1934–2010), who became a director at CBS Television, and a younger sister, Mary Carroll (1944–2024), who became a photo editor for <i>People</i> magazine.
					</p>
					<p>
						The Mardens lived in Briarcliff Manor, New York, a small suburban town thirty-two miles north of New York City, not far from the Hudson River. Brice attended the local public schools through high school. An early career interest (that may have been satisfied years later) was hotel administration: “I was really just impressed with the way hotels were run. Conrad Hilton was an idol, you know. I'd read his book in envy. Cornell has the best hotel school, and I really wanted to go there up until the second semester in my senior year in high school. I'd applied to all these hotel administration schools. And then I said I don't want to do that, I said I wanted to study art."<a href="#footnote1" ><sup>1</sup></a>
					</p>
					<p>
						Looking back years later, he told his daughter Mirabelle: “I think I was in the seventh grade. . . . I used to go wander in the woods, and one time I was in this little grove. I fell asleep and woke up lying in these reindeer ferns, and it just seemed to me that when I woke up, I was different than when I went to sleep. I always took that as the point that I became an artist.”<a href="#footnote2"><sup>2</sup></a>
					</p>
					<p>
						Fred Sergenian, the father of a good friend, was an artist and head of the art department at the advertising agency Young &amp; Rubicam before retiring to paint full-time; he proved to be a big influence on Marden during his high school years. Sergenian gave Marden a subscription to <i>Artnews</i> and his wife, Marjorie, took her son John and Marden to art museums in New York. He remembers visiting the Museum of Modern Art in New York “and having an experience looking at a [Constantin] Brancusi. It was a moment where you figure out something more is going on here than what you’re seeing. I think it was my first real aesthetic experience.”<a href="#footnote3"><sup>3</sup></a> In his later high school years, too, Marden became interested in “an alternative lifestyle” and began hitchhiking into New York to hang out in Greenwich Village. He went to the jazz club Birdland to hear music and was captivated by the people and surroundings he observed there. He recalled, “I figured I'd become this artist and go to Greenwich Village which is where it is supposed to be going on, where it was happening then.”<a href="#footnote4"><sup>4</sup></a>
					</p>
					<H2>
						1956–57
					</H2>
					<p>
						In the fall, Marden began his freshman year at Florida Southern College, Lakeland. He said: “I went down there and just immediately hated it the second I saw it. The idea was to go there and take liberal arts for a year and take art courses to see if I was interested.”<a href="#footnote5" name="ednref5"><sup>5</sup></a> He did find one encouraging teacher in Dean Eckert, who gave him passes and sent him to the museums in New York during holidays. Over the winter break, Marden visited the retrospective of Jackson Pollock’s art at the Museum of Modern Art, New York, and was excited by it.
					</p>
					<H2>
						1958
					</H2>
					<p>
						Early in the year, at the Sidney Janis Gallery, New York, Marden saw Mark Rothko’s paintings for the first time. He recalled: “The paintings seemed huge because the gallery was small and divided into several rooms with low ceilings—these 9.5 ft works were literally covering the walls. When it’s just you and several of these paintings in one room, it is an incredible experience. . . . I realized what I liked about Abstract Expressionism was that it didn’t pay to get terribly analytical about it. It was better if you just went with the painting.”<a href="#footnote6"><sup>6</sup></a>
					</p>
					<p>
						In the fall, Marden transferred to Boston University’s School of Fine and Applied Arts, graduating with a BFA in 1961. The classes there were “very academically oriented,” and the teachers revered Expressionist painters such as Oskar Kokoschka (1886–1980) and Max Beckmann (1884–1950). He credits Reed Kay, his second- and third-year painting instructor, for forming him as an artist: “Reed Kay would talk more about old master paintings and color and you could discuss a Matisse color painting. . . and just the whole idea of . . . seeing a dark against a dark. . . . We were just . . . learning how to look at things. That was a great thing about Boston University, boy, they really made you look at things.” Marden made abstract paintings outside of the school curriculum and got some encouragement from the only two “outsiders” who worked abstractly, Hugh Townley and Arthur Hoener.<a href="#footnote7"><sup>7</sup></a>&nbsp;
					</p>
					<p>
						Besides meeting other artists—including the painters Pat Steir, Alan Cote, Harvey Quaytman, and Bob Neuwirth (who later became a well-known musician and was Bob Dylan’s road manager for a while but remained a good friend throughout Marden’s life)—and visiting the Boston museums frequently, Marden participated in the folk music scene in Cambridge, Massachusetts, spending time at Club 47, where the singer Joan Baez started her career and folk singer Eric Von Schmidt and blues musicians such as Reverend Gary Davis and Lightnin’ Hopkins were playing.
					</p>
