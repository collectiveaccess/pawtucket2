						2010
					</H2>
					<p>
						Marden was commissioned by Emily and Mitch Rales to create a painting for the building that was being designed by the architect Thomas Phifer to house the Rales’s collection at their private museum, Glenstone, in Potomac, Maryland. Marden was given free rein to determine the size and scale of the room to house his work and the lighting. The project would occupy him until its completion in 2015. The work, <i>Moss Sutra with the Seasons</i> (no. 419), was installed in 2018.&nbsp;
					</p>
					<p>
						On October 29, <i>Brice Marden: Letters</i> opened at the Matthew Marks Gallery<i>, </i>New York.
					</p>
					<H2>
						2011
					</H2>
					<p>
						On January 29, Marden delivered a lecture in Houston as part of the series <i>The Rothko Chapel and the Transformative Power of Art</i>, titled: “About Painting and What it Can Do.” Speaking of this talk, given in the chapel, Marden said, “That talk was about doubt, and there is this whole thing about how Rothko never saw the chapel hung, so there’s this doubt about it. I said this, ‘You look at these things, you know he has no doubt about this.’ I think about Rothko and the chapel situation a lot, I really do. I think he really knew what he was doing and had nothing to worry about.”<a href="#footnote56"><sup>56</sup></a>
					</p>
					<H2>
						2012
					</H2>
					<p>
						On April 21, <i>Brice Marden: New Paintings</i> opened at Matthew Marks Gallery, New York. It included a new group of paintings on marble, among other works.
					</p>
					<p>
						On May 14, Marden delivered a lecture at Tate Modern in London as part of the American Artist Lecture Series, sponsored by the Tate and the US Art in Embassies program. (See "This is what I do, this is what I try to do"[link].)
					</p>
					<H2>
						2013
					</H2>
					<p>
						The Mardens purchased a hotel in Tivoli, now called Hotel Tivoli, to save a local business. They remodeled the interior and opened it with a restaurant in 2014. Marden said of the purchase, “There’s always been a place here, and it’s good that it stays going.”<a href="#footnote57"><sup>57</sup></a>
					</p>
					<p>
						Marden joined the board of directors for the Dia Art Foundation, serving until 2015.&nbsp;
					</p>
					<H2>
						2015
					</H2>
					<p>
						The Mardens purchased a riad in Marrakech. After acquiring the property, Marden said: “Marrakech is this pink city. . . . I think one of the first things I’ll do is a painting based on the pinks.”<a href="#footnote58"><sup>58</sup></a>
					</p>
					<p>
						On November 7, <i>Brice Marden: New Paintings and Drawings</i> opened at Matthew Marks Gallery, New York; the paintings, along with five new works, traveled the following January to the gallery’s Los Angeles locations. The exhibition included the <i>Nevis Stele</i> group (nos. 420–424), <i>Eastern Moss</i> (no. 415), and <i>Uphill 4</i> (no. 407), among other paintings.
					</p>
					<H2>
						2017
					</H2>
					<p>
						In January, Marden joined Gagosian gallery.&nbsp;
					</p>
					<p>
						Marden received an honorary doctor of fine arts degree from Bard College in Annandale-on-Hudson, New York.
					</p>
					<p>
						Marden was diagnosed with cancer and began chemotherapy. Asked how the illness was affecting his work, he said, “I guess I was lucky. . . . I have been able to work through it all. It hasn’t made me hurry things up. It hasn’t made me work any differently. It’s just been an extra thing to think about.”<a href="#footnote59"><sup>59</sup></a> He underwent periodic treatments for cancer during his remaining years.
					</p>
					<p>
						On October 4, <i>Brice Marden</i> opened at Gagosian’s Grosvenor Hill gallery in London. The show included the <i>Terre Verte</i> group of paintings (nos. 435–444).
					</p>
					<H2>
						2018
					</H2>
					<p>
						Marden provided the images for the sets of <i>Four Quartets</i>, a dance performance based on T. S. Eliot’s poem, choreographed by Pam Tanowitz, with music by Kaija Saariaho, held at the Fisher Center at Bard College. The images enlarged to provide massive sets were <i>Painting Study II</i>, a drawing from 1980, <i>Thira</i> (no. 178), <i>Uphill 4</i>, and <i>Rocks</i> (no. 464; in progress).
					</p>
					<H2>
						2019
					</H2>
					<p>
						On February 2, <i>Brice Marden: Morocco</i> opened at Musée Yves Saint Laurent in Marrakech and traveled to Gagosian Paris.
					</p>
					<p>
						On November 9, <i>Brice Marden: It reminds me of something, and I don’t know what it is.</i> opened at Gagosian’s gallery at 980 Madison Avenue, New York. The exhibition included <i>Yellow Painting</i> (no. 458), <i>Oued</i> (no. 456), and <i>Withwhite</i> (no. 460), among others.
					</p>
