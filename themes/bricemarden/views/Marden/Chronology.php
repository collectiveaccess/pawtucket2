					<H2>
						1990
					</H2>
					<p>
						In April, Marden delivered “Notes on Late Works of Jackson Pollock” at the National Museum of American Art, Washington, DC (now the Smithsonian American Art Museum). Marden gave a defense of Pollock’s late work, which he felt had been overlooked by scholars. Pollock’s work was a particular interest of Marden’s as he worked on a way to integrate more drawing into his own paintings.
					</p>
					<H2>
						1991
					</H2>
					<p>
						Marden began working with Thomas Ammann Fine Art, Zurich, which represented his work in Europe. He continued to work with the gallery until the death of Doris Ammann in 2021.
					</p>
					<p>
						On January 15, <i>Brice Marden: The Grove Group</i> opened at Gagosian Gallery, 980 Madison Avenue, New York, marking the first time that the full group—including five paintings, five drawings, and numerous studies—was shown together.&nbsp;
					</p>
					<p>
						On March 23, <i>Connections: Brice Marden</i>, exploring the artist’s work in the context of the larger museum collection, opened at the Museum of Fine Arts, Boston.&nbsp;
					</p>
					<p>
						On May 7, <i>Brice Marden: Recent Drawings and Etchings</i> opened at the Matthew Marks Gallery, New York. Marden, who had encouraged Marks to open his gallery, continued his affiliation with the dealer until the end of 2016.
					</p>
					<p>
						The Mardens acquired Rainbow Farms in Eagles Mere, Pennsylvania, not far from where Helen grew up. The property there is densely forested, with natural springs running through it. He described his studio there as the most “Zen-like” of his workplaces.<a href="#footnote38"><sup>38</sup></a> It was in a barn surrounded by trees: “I’m in the forest there, and it’s really filtered light. . . . The studio’s really dark—I can barely see despite the lamps I have set up.”<a href="#footnote39"><sup>39</sup></a> He said his work there was “wet and cold.”<a href="#footnote40"><sup>40</sup></a>&nbsp;
					</p>
					<p>
						On October 17, <i>Brice Marden: Cold Mountain</i>—an exhibition of drawings, prints, and paintings based on the writings of the Chinese poet Han Shan, or Cold Mountain—opened at the Dia Center for the Arts in New York. It traveled to the Walker Art Center, Minneapolis; the Menil Collection, Houston; the Museo Nacional Centro de Arte Reina Sofía, Madrid; and the Kunstmuseum Bonn, Germany. It was curated by Gary Garrels, and the catalogue contained a long essay by Brenda Richardson explaining Marden’s interest in Asian art.
					</p>
					<H2>
						1992
					</H2>
					<p>
						On February 26, <i>Brice Marden: Prints 1961–1991</i>, opened at Tate Gallery, London. It traveled to Musée d’Art Moderne de la Ville de Paris and the Baltimore Museum of Art. The catalogue, by Jeremy Lewison, was a complete and comprehensive history of the prints Marden had made up to 1991.
					</p>
					<H2>
						1993
					</H2>
					<p>
						On May 16, <i>Brice Marden</i>—an exhibition of paintings, drawings, and prints—opened at the Museum für Gegenwartskunst in Basel and traveled to the Museum Fridericianum, Kassel, Germany.
					</p>
					<p>
						On October 9, <i>Brice Marden: Paintings 1985–1993</i> opened at the Kunsthalle Bern and traveled to the Vienna Secession.&nbsp;
					</p>
					<H2>
						1995
					</H2>
					<p>
						On October 13, <i>Brice Marden</i> opened at the Matthew Marks Gallery, New York. It included <i>Skull with Thought</i> (no. 325), <i>Light in the Forest</i> (no. 328), and <i>The Golden Pelvic</i> (no. 329).
					</p>
					<p>
						In November, Marden visited Japan at the invitation of the National Museum of Modern Art, Tokyo, where the exhibition <i>A Perspective on Contemporary Art: Painting–Singular Objects</i>, which included his work, was on view. He went to visit the temples and gardens in Kyoto while he was there, later referring to the moss garden at the temple Saihō-ji as “totally calming and very beautiful. The dry stone waterfall there is my favorite image.”<a href="#footnote41"><sup>41</sup></a> Using the opportunity to travel further in the East, he “decided to go on to China afterwards. I had also been reading the <i>Tao Te Ching</i>[a foundational text of Taoism] and studying the <i>I Ching</i>. For years I would throw the <i>I Ching</i> every day—which forced me to read it and begin to absorb some of the thinking.”<a href="#footnote42"><sup>42</sup></a> In another account, he stated, “I went to China to look at the scholar rocks in gardens, not the little scholar ones, but the big Taihu rocks.”<a href="#footnote43"><sup>43</sup></a> It was in Suzhou, where Marden saw the famous rock “Cloud-Capped Peak” in the Lingering Garden, that he “got it,” that a rock could be the subject of veneration.<a href="#footnote44"><sup>44</sup></a> Marden also traveled to Hong Kong on this trip.
					</p>
					<p>
						On November 28, Marden presented a lecture at the China Institute in New York titled “Chinese Calligraphy: A Contemporary View.” Speaking of his interest in the topic, he explained, “It’s more the idea of the energy, and you know, the look, rather than some sort of knowledge about calligraphy, which I just identified with—on a mostly visual point of view.”<a href="#footnote45"><sup>45</sup></a>
					</p>
					<p>
						Marden purchased his first scholar’s rock for what would become a small collection. He also collected “Olmec stones and things like that.”<a href="#footnote46"><sup>46</sup></a>
					</p>
					<H2>
						1996
					</H2>
					<p>
						On June 10, <i>Brice Marden</i> opened at Thomas Ammann Fine Art AG in Zurich. His first solo show with the gallery, it included <i>Suzhou</i> (no. 335), <i>China Painting</i> (no. 336), and <i>Tang Dancer</i> (no. 333), among others.
					</p>
					<p>
						Marden was asked by the Center for Constitutional Rights in New York to design a medal to be given to recipients of the <i>William Moses Kunstler Award for Racial Justice</i>. Kunstler (1919–1995) was a civil rights advocate and lawyer best known for having defended the Chicago Seven, a group of individuals involved in anti–Vietnam War and other countercultural protests who had been charged with conspiracy and intent to incite riot during the 1968 Democratic Convention in Chicago. Marden and Kunstler met through their daughters, who attended the same school, and became close friends. Speaking of Kunstler, Marden said: “I have this really good friend who died last year—William Kunstler, the lawyer. I thought a lot about Bill and how much I really miss him—have missed him—and how I didn’t even begin to understand the closeness of our relationship when he was still alive. . . . I made this bronze, the <i>William Moses Kunstler Award for Racial Justice</i>, and it’s my epitaph for Bill.”<a href="#footnote47"><sup>47</sup></a> The medal took the form of a Chinese <i>bi</i>, an ancient flat jade disk with a circular hole in the middle. The disks were associated with heaven or the cosmos and sometimes buried with the dead. Recipients of the award included, among others, Akil Al-Jundi and Herbert Blyden, both former prisoners turned advocates for inmates; the actor Danny Glover; and President Jean-Bertrand Aristide of Haiti.
					</p>
					<H2>
						1997
					</H2>
					<p>
						On May 5, <i>Brice Marden: Two New Paintings with Five Tang Dynasty Stone Epitaphs</i> opened at Matthew Marks Gallery, New York. The exhibition included two paintings from the <i>Epitaph&nbsp;</i>group (nos. 341 and 342).
					</p>
					<p>
						On July 2, <i>Brice Marden: Work Books, 1964–1995</i>, opened at the&nbsp;Staatliche Graphische Sammlung in Munich. It traveled to the Kunst Museum Winterthur in Switzerland; the Wexner Center for the Arts at Ohio State University in Columbus; and the Harvard University Art Museums in Cambridge, Massachusetts. The show included many of the notebooks or sketchbooks that Marden carried with him when he traveled and filled with drawings and notes.
					</p>
					<H2>
						1998
					</H2>
					<p>
						Marden became a member of the American Academy of Arts and Letters.
					</p>
					<p>
						On November 20, <i>Brice Marden: Drawings</i> opened at the Whitney Museum of American Art in New York.
					</p>
					<H2>
						1999
					</H2>
					<p>
						On February 14, <i>Brice Marden: Work of the 1990s</i>, opened at the Dallas Museum of Art. It traveled to the Hirshhorn Museum and Sculpture Garden, Smithsonian Institution, Washington, DC; the Miami Art Museum (now the Pérez Art Museum Miami); and the Carnegie Museum of Art, Pittsburgh.
					</p>
					<p>
						Marden moved his New York studio to 170 Varick Street.
					</p>
					<p>
						On October 3, <i>Work Books and Series</i>, a version of the earlier <i>Work Books</i> exhibition, opened at the Museum of Fine Arts in Houston.
					</p>
