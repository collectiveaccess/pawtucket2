<p>through this layering, diverse drawing 
opportunities will open up. (All these layers are joinings 
of “characters,” marks&mdash;my own fictitious calligraphy.)
The layering process where the image reveals 
itself by coming up&mdash;emerging from&mdash;positive 
application (that’s where I draw something down) then negation 
(which is [when] I get the whole thing working and then paint over the 
whole thing, scrape it down, and see what starts talking to me), 
<br>search, reapplication, 
<br>negation, search. (explain)
<br>This is where we are now. </p>

<div class="ms-4">The ultimate aim of painting is not decorative 
beauty but truth. What is <i>truth?</i> It must 
not be confused with formal resemblance; 
indeed, <i>formal resemblance</i> only reaches the 
appearance of things, whereas the function 
of truth is to capture their essence. 
<br/>&mdash;Shi Tao<a href="#footnote4"><sup>4</sup></a></div>

