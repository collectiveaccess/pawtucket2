<p>I’ve just been in Hydra, Greece, where there 
<br/>is the tail end of the spring burst of wildflowers and 
<br/>the return of some warming sun. In a walled garden I made 
<br/>notes for this talk. Roses, jasmine, lavender 
<br/>blooming. I was working a painting on marble, started 
<br/>last summer. I was with my beautiful wife. We read 
<br/>poems by Greek poets, drank coffee, ate fruit. Close 
<br/>to ideal. I arrive here in London and find my notes 
<br/>way too romantic, complicated, and confused. </p>

<p>Things like “my embrace of the square”&mdash;infinite 
<br/>possibilities evolving into repetitious clichés&mdash;the belief 
<br/>in the hand (arm to body), so trained as it may be, 
<br/>can still deliver individuality or, through muscularity, 
<br/>express and deliver the inner workings of the human with 
<br/>infinite subtlety&mdash;hand to human connection 
<br/>dance&mdash;inner expression brought out / the jasmine 
<br/>window&mdash;capturing the evocation, being <i>about</i> something 
<br/>not a picture of it. Detachment, transformation, is 
<br/>balance form?&mdash;perfect balance&mdash;to follow the 
<br/>dictates of the image / ambiguity&mdash;<i>inquiétant</i>&mdash;
<br/>oppositional forces&mdash;opposites&mdash;equals&mdash;yin-yang 
<br/>acknowledged and <i>allowed</i> to turn into feelings 
<br/>creating an elevated sense, which puts you back 
<br/>in touch with being human in this environment. 
<br/>Subject matter&mdash;I acknowledge nature and form as my 
<br/>guides&mdash;form as incorrectable&mdash;form is the incorrectable 
<br/>attainment. </p>

<p>Stop the motion, freeze the energy, only to show 
<br/>the motion, keep it moving, retaining the 
<br/>energy. “Perpetuate the validity of vagueness.”
<br/>“Pictures must be miraculous,” Mark Rothko. 
<br/>In the Acropolis Museum&mdash;the Greek light on 
<br/>the marble of the sculptures&mdash;it’s working, everything 
<br/>becomes enhanced&mdash;the Peplos Kore&mdash;in perspective&mdash;
<br/>in the distance. Giacometti&mdash;the specifics of her subtleties
<br/>the light, the marble. Images quivering on the
<br/>brink of becoming alive.
</p>
<p>
I like to work within given restraints&mdash;a given 
<br/>shape, the wall, a given space.
<br/>I like number systems&mdash;I have worked with a grid of 4 and 3&mdash;
<br/>4 representing the elements and 3 the Trinity.
<br/>And I had a numerologist friend who told me my number was 6. 
<br/>So I made a painting called <i>The Propitious Garden of Plane Image</i>
<br/>(Plane Image is just another way I refer to myself or the studio or 
<br/>whatever).
<br/>The painting was made up of 6 panels&mdash;each with 6 colors, 
<br/>they were 4 x 6 [feet]&mdash;which is 24&mdash;which is 6. I was beginning to feel
<br/>this was some sort of ultimate self-portrait.
<br/>I showed two of them in a show at the Modern [Museum of Modern Art] in New York<a href="#footnote2"><sup>2</sup></a>.  I
<br/>invited my friend Jeffrey [Brennan] to come to the opening, and he said, 
<br/>“Why was I invited?” And I said, “You said my number was 6. 
<br/>I’ve made all these paintings!” He said, “Your number is fifteen!”
<br/>So now I’m working on fifteen. I call them Stele Paintings.
<br/>There was a poet named Victor Segalen; he was a very interesting 
<br/>guy, a doctor. It was he who bought all the Gauguins that came up 
<br/>for auction in Tahiti. And he was an early Orientalist. And he 
<br/>wrote a book of poems based on these stele, which were stone 
<br/>tablets they put up, inscribed with poetry or instructions on how to 
<br/>deal with your life. So I have five of these in three different 
<br/>studios, each with three lines of five characters. And I’m working 
<br/>on them in the different studios because I want to see what the 
<br/>differences will be by being in different places. So I have a group 
<br/>in Nevis, in the Caribbean. And I have a set in New York City. 
<br/>And I have a set at upstate in Tivoli. They haven’t gone very far.
<br>But it’s a plan.</p>

<p>avoidance of the givens. The square (the perfect abstraction) 
<br/>always keep it a little off
<br/>acceptance of the given&mdash;my recent embrace of the square.</p>

<p>I had these extra 6 x 8 foot canvases around the studio, and I’d 
<br/>been doing these horizontal paintings, and I just turned it vertical, 
<br/>did a 6 x 6 foot square. And it didn’t look square. And that
<br/>became part of what. . . .</p>
 
<p class="ms-4 mb-3">What I am doing now</p>
<p>I am making a painting to be titled <i>The Moss 
<br/>Sutra<a href="#footnote3"><sup>3</sup></a></i> &mdash; it consists of a large center panel 
9' x 15'&mdash;
<br/>4 side panels 8' x 6' each. The center panel is divided into
<br/>4 horizontal areas, the largest being the center, which holds a grid 
<br/>of thirty-five vertical lines of five “characters” each. I took this 
<br/>form from a piece of calligraphy that an expert told me
<br/>was a sutra. I love moss. A favorite image of mine is the Musō Soseki
<br/>dry stone waterfall in the Moss Garden (Saihō-ji) in Kyoto, Japan. </p>

