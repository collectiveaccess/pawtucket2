<p>I’ve just been in Hydra, Greece, where there 
is the tail end of the spring burst of wildflowers and 
the return of some warming sun. In a walled garden I made 
notes for this talk. Roses, jasmine, lavender 
blooming. I was working a painting on marble, started 
last summer. I was with my beautiful wife. We read 
poems by Greek poets, drank coffee, ate fruit. Close 
to ideal. I arrive here in London and find my notes 
way too romantic, complicated, and confused. </p>

<p>Things like “my embrace of the square”&mdash;infinite 
possibilities evolving into repetitious clichés&mdash;the belief 
in the hand (arm to body), so trained as it may be, 
can still deliver individuality or, through muscularity, 
express and deliver the inner workings of the human with 
infinite subtlety&mdash;hand to human connection 
dance&mdash;inner expression brought out / the jasmine 
window&mdash;capturing the evocation, being <i>about</i> something 
not a picture of it. Detachment, transformation, is 
balance form?&mdash;perfect balance&mdash;to follow the 
dictates of the image / ambiguity&mdash;<i>inquiétant</i>&mdash;
oppositional forces&mdash;opposites&mdash;equals&mdash;yin-yang 
acknowledged and <i>allowed</i> to turn into feelings 
creating an elevated sense, which puts you back 
in touch with being human in this environment. 
<br/>Subject matter&mdash;I acknowledge nature and form as my 
guides&mdash;form as incorrectable&mdash;form is the incorrectable 
attainment. </p>

<p>Stop the motion, freeze the energy, only to show 
the motion, keep it moving, retaining the 
energy. “Perpetuate the validity of vagueness.”
“Pictures must be miraculous,” Mark Rothko. 
In the Acropolis Museum&mdash;the Greek light on 
the marble of the sculptures&mdash;it’s working, everything 
becomes enhanced&mdash;the Peplos Kore&mdash;in perspective&mdash;
in the distance. Giacometti&mdash;the specifics of her subtleties
the light, the marble. Images quivering on the
brink of becoming alive. </p>

I like to work within given restraints&mdash;a given 
shape, the wall, a given space.<br>
I like number systems&mdash;I have worked with a grid of four and three&mdash;
four representing the elements and three the Trinity.<br>
And I had a numerologist friend who told me my number was six. 
So I made a painting called <i>The Propitious Garden of Plane Image</i>
(Plane Image is just another way I refer to myself or the studio or 
whatever).<br>
The painting was made up of six panels&mdash;each with six colors, 
they were four by six [feet]&mdash;which is twenty-four&mdash;which is six. I was beginning to feel <br>
this was some sort of ultimate self-portrait. <br>
I showed two of them in a show at the Modern [Museum of Modern Art] in New York<a href="#footnote2"><sup>2</sup></a>.  I invited my friend Jeffrey [Brennan] to come to the opening, and he said, 
“Why was I invited?” And I said, “You said my number was six. 
I’ve made all these paintings!” He said, “Your number is fifteen!”
So now I’m working on fifteen. I call them Stele Paintings.
<br/>There was a poet named Victor Segalen; he was a very interesting 
guy, a doctor. It was he who bought all the Gauguins that came up 
for auction in Tahiti. And he was an early Orientalist. And he 
wrote a book of poems based on these stele, which were stone 
tablets they put up, inscribed with poetry or instructions on how to 
deal with your life. So I have five of these in three different 
studios, each with three lines of five characters. And I’m working 
on them in the different studios because I want to see what the 
differences will be by being in different places. So I have a group 
in Nevis, in the Caribbean. And I have a set in New York City. 
And I have a set at upstate in Tivoli. They haven’t gone very far.
<br>But it’s a plan.</p>

<p>avoidance of the givens. The square (the perfect abstraction) 
always keep it a little off<br>
acceptance of the given&mdash;my recent embrace of the square.</p>

<p>I had these extra six-by-eight-foot canvases around the studio, and I’d 
been doing these horizontal paintings, and I just turned it vertical, 
did a six-by-six-foot square. And it didn’t look square. And that
 became part of what.…</p>
 
<p class="ms-4 mb-3">What I am doing now</p>
<p>I am making a painting to be titled <i>The Moss 
Sutra<a href="#footnote3"><sup>3</sup></a></i> &mdash; it consists of a large center panel 
nine feet by fifteen feet&mdash;four side panels eight feet by six feet
 each. The center panel is divided into four horizontal
 areas, the largest being the center, which holds a grid 
of thirty-five vertical lines of five “characters” each. I took this 
form from a piece of calligraphy that an expert 
told me was a sutra. I love moss. A favorite 
image of mine is the Musō Soseki dry stone waterfall
 in the Moss Garden (Saihō-ji) in Kyoto, Japan. </p>

<div class="mb-3">The side panels are to be painted as the seasons.
